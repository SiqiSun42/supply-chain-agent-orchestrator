from __future__ import annotations

import re
from typing import Any

from orchestrator.supply_chain.constants import DEFAULT_DB_PATH
from orchestrator.supply_chain.queries import query_supplier_offers

PROCUREMENT_INBOX_EMAIL = "procurement@plant.example.com"

_SUPPLIER_RE = re.compile(r"\b(SUP-\d{2})\b", re.IGNORECASE)
_PART_RE = re.compile(r"\b(HYD-\d{2})\b", re.IGNORECASE)
_QTY_RE = re.compile(r"\b(\d{1,6})\s*units?\b", re.IGNORECASE)


def is_purchase_order_dispatch_task(task: str) -> bool:
    t = task.lower()
    if not _PART_RE.search(task):
        return False
    if not _SUPPLIER_RE.search(task):
        return False
    has_po = any(
        phrase in t
        for phrase in (
            "purchase order",
            "place a purchase order",
            "place an order",
            "order from",
            "send to procurement",
            "procurement",
        )
    )
    return has_po or ("order" in t and "supplier" in t)


def parse_purchase_order_dispatch_task(task: str) -> dict[str, Any]:
    part = _PART_RE.search(task)
    supplier = _SUPPLIER_RE.search(task)
    qty_match = _QTY_RE.search(task)
    product_code = part.group(1).upper() if part else "HYD-08"
    supplier_name = supplier.group(1).upper() if supplier else "SUP-01"
    qty = int(qty_match.group(1)) if qty_match else 1000
    return {
        "product_code": product_code,
        "supplier_name": supplier_name,
        "qty": qty,
    }


def check_po_feasibility(
    supplier_name: str,
    product_code: str,
    qty: int,
    *,
    db_path=DEFAULT_DB_PATH,
) -> tuple[bool, str, dict[str, Any] | None]:
    payload = query_supplier_offers(product_code, db_path=db_path)
    offers = {str(row["supplier_name"]): row for row in payload["offers"]}
    offer = offers.get(supplier_name)
    if offer is None:
        return (
            False,
            f"Supplier {supplier_name} has no offer row for {product_code} in the database.",
            None,
        )
    available = int(offer["qty_available"])
    if qty > available:
        return (
            False,
            (
                f"Cannot place order for {qty} units: {supplier_name} only has "
                f"{available} units available for {product_code}."
            ),
            offer,
        )
    return True, "", offer


def build_purchase_order_email(
    *,
    product_code: str,
    supplier_name: str,
    qty: int,
    offer: dict[str, Any],
    body_override: str | None = None,
) -> dict[str, Any]:
    unit_price = float(offer["unit_price"])
    lead_days = int(offer["lead_days"])
    total = round(unit_price * qty, 2)
    default_body = (
        f"Procurement team,\n\n"
        f"Please review and release the following purchase order request.\n\n"
        f"Supplier: {supplier_name}\n"
        f"Product: {product_code}\n"
        f"Quantity: {qty}\n"
        f"Unit price: ${unit_price:.2f}\n"
        f"Estimated total: ${total:,.2f}\n"
        f"Lead time (days): {lead_days}\n\n"
        f"This request was generated by the operations agent for leadership routing. "
        f"Procurement owns release to the supplier.\n\n"
        f"Regards,\n"
        f"Meridian Ops Agent"
    )
    body = body_override.strip() if body_override and body_override.strip() else default_body
    subject = f"PO request: {qty} x {product_code} from {supplier_name}"
    return {
        "to": PROCUREMENT_INBOX_EMAIL,
        "subject": subject,
        "body": body,
        "purpose": "purchase_order_dispatch",
        "product_code": product_code,
        "supplier_name": supplier_name,
        "qty": qty,
        "unit_price": unit_price,
        "lead_days": lead_days,
        "estimated_total": total,
    }


def build_send_email_args_for_po(task: str, *, db_path=DEFAULT_DB_PATH) -> dict[str, Any]:
    parsed = parse_purchase_order_dispatch_task(task)
    ok, reason, offer = check_po_feasibility(
        parsed["supplier_name"],
        parsed["product_code"],
        parsed["qty"],
        db_path=db_path,
    )
    if not ok or offer is None:
        raise ValueError(reason)
    email = build_purchase_order_email(
        product_code=parsed["product_code"],
        supplier_name=parsed["supplier_name"],
        qty=parsed["qty"],
        offer=offer,
    )
    return email


def apply_po_email_revision(args: dict[str, Any], *, revised_body: str) -> dict[str, Any]:
    text = revised_body.strip()
    if not text:
        raise ValueError("revised_body must be non-empty")
    updated = dict(args)
    updated["body"] = text
    updated["revision_count"] = int(args.get("revision_count") or 0) + 1
    return updated
